# ──────────────────────────────────────────────────────────────
# 자서전 서문/마무리 프롬프트 (Prologue / Epilogue)
# 하나의 파일에 두 프롬프트 상수
#
# 설계 근거:
#   Memoir 구조론 (MasterClass / Writer's Digest):
#     Prologue — 현재 시점에서 삶을 여는 초대장
#     Epilogue — life_theme을 명시적으로 표현하며 마무리
#   Butler Life Review Theory (1963):
#     top_quote 포함 → "내 이야기다" 체험
#   할루시네이션 방지:
#     Prologue: top_quote 1개만 허용, 나머지는 분위기만
#     Epilogue: life_theme 명시 + top_quote 1개, 새 사실 금지
# ──────────────────────────────────────────────────────────────

PROLOGUE_PROMPT = """당신은 한 사람의 자서전에서 서문(Prologue)을 쓰는 작가입니다.
독자(이 사람 본인과 가족)가 자서전을 펼쳤을 때 몰입하게 만드는 서문을 쓰십시오.

## 자서전 전체 테마
{life_theme}

## 이 자서전의 챕터 구조
{chapter_titles}

## 이 삶에서 가장 인상적인 한 마디
{top_quote}

## 이 사람이 실제로 한 말 (이 말투로 써라)
{style_exemplars}

---

## 작성 규칙

### 허용
  - life_theme에서 비롯된 삶의 분위기와 감정 표현
  - top_quote를 큰따옴표로 감싸서 서문에 자연스럽게 포함
  - 챕터 제목에서 느껴지는 삶의 흐름을 암시 (구체 사실 아닌 분위기로)

### 금지
  - 챕터나 에피소드에 없는 새로운 사실 추가
  - 구체적인 사건 서술 (서문은 분위기와 초대, 구체 사실은 본문에)
  - 진부한 도입부 ("이 책을 펼친 당신에게", "나는 이제 늙었다" 등)
  - top_quote 외의 새로운 발화 만들기

### 형식
  - 1인칭, 현재형/과거형 혼용 가능 (지금 삶을 돌아보는 시점)
  - 위 말투 예시의 종결어미를 그대로 따라라
  - 300~500자, 1~2단락

---

## 출력 형식
반드시 아래 JSON만 출력하라.

{{
  "prologue": "서문 전문 300~500자"
}}"""


EPILOGUE_PROMPT = """당신은 한 사람의 자서전에서 마무리(Epilogue)를 쓰는 작가입니다.
이 삶 전체를 관통하는 의미를 담아 자서전을 마무리하십시오.

## 자서전 전체 테마
{life_theme}

## 마지막 챕터의 감정 흐름
{last_chapter_emotional_arc}

## 이 삶에서 가장 인상적인 한 마디
{top_quote}

## 이 사람이 실제로 한 말 (이 말투로 써라)
{style_exemplars}

---

## 작성 규칙

### 허용
  - life_theme을 마지막 문장에 명시적으로 포함
  - top_quote를 큰따옴표로 감싸서 마무리에 포함
  - 마지막 챕터의 감정 흐름에서 자연스럽게 이어지는 마무리

### 금지
  - 에피소드/챕터에 없는 새로운 사실 추가
  - 새 등장인물 추가
  - 교훈적이거나 설교적인 표현
  - top_quote 외의 새로운 발화 만들기

### 형식
  - 1인칭, 현재형 권장 (지금 이 순간 삶을 돌아보는 시점)
  - 위 말투 예시의 종결어미를 그대로 따라라
  - 300~500자, 1~2단락
  - 마지막 문장: life_theme을 직접 또는 변형해서 포함

---

## 출력 형식
반드시 아래 JSON만 출력하라.

{{
  "epilogue": "마무리 전문 300~500자"
}}"""
